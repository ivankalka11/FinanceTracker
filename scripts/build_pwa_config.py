"""Generate pwa/config.js (and the PNG app icons, if missing) for the V2 PWA.

Reads SUPABASE_URL and SUPABASE_PUBLISHABLE_KEY from the real environment
first (so a host such as Cloudflare Pages can supply them), then from the
root .env. Only these two browser-safe values are written; the secret key
never leaves .env.

Usage (from the project root):
    python scripts/build_pwa_config.py
"""
import json
import struct
import sys
import zlib
from pathlib import Path
import os

ROOT = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(ROOT / "TelegramBot"))
import env_loader  # noqa: E402,F401  (loads the root .env; real env vars win)

KEYS = ("SUPABASE_URL", "SUPABASE_PUBLISHABLE_KEY")
BG, ACCENT = (0x0F, 0x0F, 0x11), (0xEE, 0x4D, 0x8C)
# three rising bars on a 512 grid, kept inside the maskable safe zone
BARS = ((156, 276, 212, 356), (228, 216, 284, 356), (300, 156, 356, 356))


def write_png(path: Path, size: int) -> None:
    """Draw the app icon with the standard library only."""
    scale = size / 512
    boxes = [tuple(round(v * scale) for v in b) for b in BARS]
    rows = bytearray()
    for y in range(size):
        rows.append(0)  # filter: none
        for x in range(size):
            inside = any(x0 <= x < x1 and y0 <= y < y1 for x0, y0, x1, y1 in boxes)
            rows.extend(ACCENT if inside else BG)

    def chunk(kind: bytes, data: bytes) -> bytes:
        body = kind + data
        return struct.pack(">I", len(data)) + body + struct.pack(">I", zlib.crc32(body))

    png = (b"\x89PNG\r\n\x1a\n"
           + chunk(b"IHDR", struct.pack(">IIBBBBB", size, size, 8, 2, 0, 0, 0))
           + chunk(b"IDAT", zlib.compress(bytes(rows), 9))
           + chunk(b"IEND", b""))
    path.write_bytes(png)


def main() -> None:
    values = {k: os.environ.get(k, "").strip() for k in KEYS}
    missing = [k for k, v in values.items() if not v]
    if missing:
        sys.exit(f"Missing in .env or environment: {', '.join(missing)}")
    if values["SUPABASE_PUBLISHABLE_KEY"].startswith("sb_secret_"):
        sys.exit("SUPABASE_PUBLISHABLE_KEY holds a secret key. Use the publishable key.")

    out = ROOT / "pwa" / "config.js"
    out.write_text(
        "// GENERATED by scripts/build_pwa_config.py. Do not edit.\n"
        f"window.FINANCE_CONFIG = {json.dumps(values, indent=2)};\n",
        encoding="utf-8",
    )
    print(f"Wrote {out.relative_to(ROOT)} ({', '.join(values)})")

    icons = ROOT / "pwa" / "icons"
    icons.mkdir(parents=True, exist_ok=True)
    for name, size in (("icon-192.png", 192), ("icon-512.png", 512), ("apple-touch-icon.png", 180)):
        if not (icons / name).exists():
            write_png(icons / name, size)
            print(f"Wrote {(icons / name).relative_to(ROOT)}")


if __name__ == "__main__":
    main()
