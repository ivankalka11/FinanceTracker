"""Builds supabase/setup_all.sql: every migration, in order, as one file.

Paste the result into the Supabase SQL Editor once to set up a NEW, empty project.
Do not run it on a project that already has the tables (use only the newer
migrations there). Re-run this script after adding or changing a migration:

    python scripts/build_supabase_setup.py
"""
from pathlib import Path

root = Path(__file__).resolve().parent.parent
files = sorted((root / "supabase" / "migrations").glob("*.sql"))
parts = [
    "-- FinanceTracker: complete database setup for a NEW Supabase project.\n"
    "-- Generated by scripts/build_supabase_setup.py from supabase/migrations/. Do not edit by hand.\n"
    "-- Run once in SQL Editor on an empty project. Included, in order:\n"
    + "".join(f"--   {f.name}\n" for f in files)
]
for f in files:
    sql = f.read_text(encoding="utf-8").replace("\r\n", "\n").strip()
    parts.append(f"\n-- ====================================================================\n"
                 f"-- {f.name}\n"
                 f"-- ====================================================================\n\n{sql}\n")
out = root / "supabase" / "setup_all.sql"
out.write_text("".join(parts), encoding="utf-8", newline="\n")
print(f"Wrote {out.relative_to(root)} ({len(files)} migrations, {out.stat().st_size // 1024} KB)")
